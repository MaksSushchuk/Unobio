def test_end_to_end_fake_lenses_flip_with_cutoff():
    now = load_bundle(FIXTURES_DIR / "il17_crohn_now.json")
    then = load_bundle(FIXTURES_DIR / "il17_crohn_2011.json")
    r_now = asyncio.run(run_lenses(now, ContextBuilder().build(now), runner(fake_lens_llm())))
    r_then = asyncio.run(run_lenses(then, ContextBuilder().build(then), runner(fake_lens_llm())))
    assert all(r.result.status == "ok" for r in [*r_now.values(), *r_then.values()])
    assert r_now["science"].result.score == 0 and r_then["science"].result.score == 3
    ids = set(now.by_id())
    for r in r_now.values():
        for c in r.result.claims:
            assert {e.evidence_id for e in c.evidence} <= ids  # every claim traceable to real evidence
    chain = r_now["science"].result.params["translation_chain"]
    assert [link["step"] for link in chain][-1] == "patient_benefit"
