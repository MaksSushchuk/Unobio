@pytest.fixture(scope="module")
def bundle():
    return load_bundle(FIXTURES_DIR / "il17_crohn_now.json")


@pytest.fixture(scope="module")
def ctx(bundle):
    return ContextBuilder().build(bundle)


def runner(fake: FakeLLM) -> AgentRunner:
    return AgentRunner(make_llm(LLMSettings(provider="fake"), fake=fake))


def science_answer(ctx) -> dict:
    """A valid science answer generated by the offline stand-in for this context."""
    prompt = lens_user_prompt("science", ctx)
    from analytics.llm import Message
    return _science(LLMRequest(messages=[Message(role="system", content=""), Message(role="user", content=prompt)]))


def strip_kill_citations(ans: dict, bundle, ctx) -> dict:
    """Same answer, but every claim cites only a neutral (non-conflict) evidence id."""
    from analytics.lenses.validation import kill_short_ids
    kills = set(kill_short_ids(bundle, ctx, "science"))
    neutral = next(i for i in ctx.lenses["science"].full_ids if i not in ctx.lenses["science"].conflict_ids)
    out = copy.deepcopy(ans)
    for c in out["claims"]:
        c["evidence"] = [{"id": neutral, "stance": "supports"}]
    assert kills
    return out


def test_prompts_render_for_every_lens(ctx):
    for lens in LENSES:
        system = lens_spec(lens).full_system_prompt()
        user = lens_user_prompt(lens, ctx)
        assert "Use only the evidence provided" in system and "Scoring rubric" in system
        assert "Answer format" in system and "$" not in user.split("## Your task")[1][:200]
        for q in LENS_DEFS[lens].questions:
            assert q in user


def test_validator_accepts_valid_and_rejects_bad_citations(bundle, ctx):
    validate = make_validator(bundle, ctx, "science")
    good = ScienceAnswer.model_validate(science_answer(ctx))
    assert validate(good) == []

    bad = strip_kill_citations(science_answer(ctx), bundle, ctx)
    bad["claims"][0]["evidence"] = [{"id": "E999", "stance": "supports"}]
    errors = validate(ScienceAnswer.model_validate(bad))
    assert any("unknown id" in e for e in errors)
    assert any("KILL SIGNAL" in e for e in errors)  # kill conflicts are no longer cited


def test_validator_rejects_ids_not_shown_to_the_lens(bundle):
    tight = ContextBuilder(ContextConfig(budget_tokens=1200)).build(bundle)
    dropped = tight.lenses["science"].dropped_ids[0]
    ans = science_answer(tight)
    ans["claims"][-1]["evidence"].append({"id": dropped, "stance": "supports"})
    errors = make_validator(bundle, tight, "science")(ScienceAnswer.model_validate(ans))
    assert any("not in your context" in e and dropped in e for e in errors)


def test_retry_fixes_missing_kill_citation(bundle, ctx):
    good = science_answer(ctx)
    bad = strip_kill_citations(good, bundle, ctx)
    fake = FakeLLM(script={"lens:science": [bad, good]})
    run = asyncio.run(run_lens("science", bundle, ctx, runner(fake)))
    assert run.result.status == "ok" and len(run.traces) == 2
    assert "KILL SIGNAL" in fake.calls[1].messages[-1].content


def test_aggregate_citation_expands_to_capped_members(bundle, ctx):
    agg_id, members = next(iter(ctx.id_map["aggregates"].items()))
    ans = science_answer(ctx)
    lc = ctx.lenses["science"]
    if agg_id not in lc.aggregate_ids:  # aggregate lives in the market lens; test the mapping there
        from analytics.lenses.fake import _market
        from analytics.llm import Message
        prompt = lens_user_prompt("market", ctx)
        ans = _market(LLMRequest(messages=[Message(role="system", content=""), Message(role="user", content=prompt)]))
